"""HYP-105 AA4-B2INT — exact two-step improper overlap and sharper all-h moments.

ALL-h graph identity for ANY simple physical graph H0 on typed grid [a]x[a]
where every physical edge changes BOTH physical coordinates:

 A0² = P2 + B2 pointwise,
 B2(u,v) counts two-walks with u.left=v.left OR u.right=v.right,
 Qx = sum_{u,v:u.left=v.left} A0²[u,v],
 Qy = sum_{u,v:u.right=v.right} A0²[u,v],
 B2_total = Qx+Qy-2m0.     (intersection only u=v)

For a physical graph generated by the ORIGINAL incidence flags of a
TRUE W(3,s), each retained flag contributes exactly two diagonals,
m0=2N0. Global pair-injection + original source-pencil counts give
 Qx=4N0+4Mg, Qy=4N0+4Mf,
 B2_total=4N0+4(Mf+Mg).

Thus tr(A0^4) <= 2||P2||_F²+2Delta B2_total
and every improper physical directed three-walk belongs either to
a bad initial 2-walk, bad terminal 2-walk, or a distance-3
coordinate-return, giving
 #improper3 <= 2Delta B2_total+Delta(Qx+Qy)
            = Delta[16N0+12(Mf+Mg)].
Under #672 established N0<=2s^4, Mf+Mg<=3s^4, Delta<=Ts,
the old constants 56T and 84T improve to 40T and 68T.

These ALL-h refinements keep the original source six-ID quantifiers
and do NOT prove the root Branch A theorem or any sharper exponent.
"""
from collections import Counter
from itertools import combinations


def _validate_grid_graph(graph):
    if not isinstance(graph,dict):
        raise ValueError("physical graph must be adjacency mapping")
    vertices=set(graph)
    for v,neighbors in graph.items():
        if (not isinstance(v,tuple) or len(v)!=2 or
            any(type(c) is not int or c<0 for c in v)):
            raise ValueError("typed grid vertices must be nonnegative integer pairs")
        if v in neighbors or not set(neighbors)<=vertices:
            raise ValueError("physical graph must be simple with all vertices")
        for w in neighbors:
            if (v not in graph[w] or v[0]==w[0] or v[1]==w[1]):
                raise ValueError("physical graph edges must be symmetric and change BOTH coordinates")


def exact_improper_path_grid_certificate(graph,*,count_three=True):
    """Physical-first exhaustive exact A0², P2, B2 and improper three-walk.

    Does not consult original source flag books, conflict_graph,
    sixset classifier, parent finite_source_certificate or pinned data.
    All graph supports include isolates if present.
    """
    _validate_grid_graph(graph)
    verts=tuple(sorted(graph))
    two=Counter();proper=Counter();bad=Counter()
    xreturns=yreturns=both=0
    for v0 in verts:
        for v1 in graph[v0]:
            for v2 in graph[v1]:
                key=(v0,v2)
                two[key]+=1
                is_x=v0[0]==v2[0]
                is_y=v0[1]==v2[1]
                xreturns+=is_x
                yreturns+=is_y
                both+=is_x and is_y
                if is_x or is_y:
                    bad[key]+=1
                else:
                    proper[key]+=1
    m=sum(map(len,graph.values()))//2
    degree=max(map(len,graph.values()),default=0)
    if both!=2*m:
        raise AssertionError("two-coordinate same-endpoint two-walk intersection !=2m")
    if xreturns+yreturns-both!=sum(bad.values()):
        raise AssertionError("B2 total original two-coordinate inclusion-exclusion broken")
    if any(two[k]!=proper[k]+bad[k] for k in two):
        raise AssertionError("physical A0²=P2+B2 pointwise broken")
    Pnorm=sum(z*z for z in proper.values())
    Bnorm=sum(z*z for z in bad.values())
    trace4=sum(z*z for z in two.values())
    cross=sum(proper[k]*bad.get(k,0) for k in proper)
    if trace4!=Pnorm+Bnorm+2*cross:
        raise AssertionError("exact physical A0 fourth moment decomposition wrong")
    if Bnorm>degree*sum(bad.values()):
        raise AssertionError("B2 maximum codegree squared envelope wrong")
    if trace4>2*Pnorm+2*degree*sum(bad.values()):
        raise AssertionError("sharper L4 bridge upper envelope wrong")
    total_three=proper_three=improper_three=bad_first=bad_last=bad_odd=0
    if count_three:
        for v0 in verts:
            for v1 in graph[v0]:
                for v2 in graph[v1]:
                    for v3 in graph[v2]:
                        total_three+=1
                        bfirst=(v0[0]==v2[0] or v0[1]==v2[1])
                        blast=(v1[0]==v3[0] or v1[1]==v3[1])
                        bodd=(v0[0]==v3[0] or v0[1]==v3[1])
                        bad_first+=bfirst
                        bad_last+=blast
                        bad_odd+=bodd
                        if bfirst or blast or bodd:improper_three+=1
                        else:proper_three+=1
        if proper_three+improper_three!=total_three:
            raise AssertionError("correct/proper 3-walk dichotomy broken")
        if bad_first>degree*sum(bad.values()) or (
            bad_last>degree*sum(bad.values())):
            raise AssertionError("new B2 two-positional 3walk union bound wrong")
        if bad_odd>degree*(xreturns+yreturns):
            raise AssertionError("odd coordinate return bound wrong")
        if improper_three>2*degree*sum(bad.values())+degree*(xreturns+yreturns):
            raise AssertionError("improved full-core improper P3 bound wrong")
    return {
        "vertices":len(verts),"edges":m,"maximum_degree":degree,
        "Qx_direct_two_coordinate_returns":xreturns,
        "Qy_direct_two_coordinate_returns":yreturns,
        "both_coordinate_returns_same_vertex":both,
        "improper_B2_total_exact":sum(bad.values()),
        "proper_P2_frobenius_squared":Pnorm,
        "improper_B2_frobenius_squared":Bnorm,
        "cross_P2_B2":cross,
        "trace_A0_fourth_exact":trace4,
        "new_fourth_upper_given_exact_P2":2*Pnorm+2*degree*sum(bad.values()),
        "old_fourth_upper_given_exact_P2":2*Pnorm+2*degree*(xreturns+yreturns),
        "direct_threewalk_total":total_three,
        "direct_proper_threewalks":proper_three,
        "direct_improper_threewalks":improper_three,
        "direct_first_second_step_improper":bad_first,
        "direct_last_second_step_improper":bad_last,
        "direct_odd_distance3_improper":bad_odd,
        "new_improper_three_upper":2*degree*sum(bad.values())+degree*(xreturns+yreturns),
        "old_improper_three_upper":3*degree*(xreturns+yreturns),
        "identity_verified_on_given_graph":True,
        "not_a_computational_proof_of_all_h":True,
    }


def genuine_original_improper_path_referee(power,f,g,core_ids=None):
    """Independent ORIGINAL source-flag FIRST books vs physical-grid FIRST.

    Use real W(3,2)/W(3,4) incidence flags. No cached fixture expected
    values, no synthetic source, no redefinition of point/line factors.
    """
    from hyp105_full_physical_degree_tail import genuine_source,physical
    from hyp105_physical_degree_energy import minimal_alphabet,_verify_typed_injections
    if type(power) is not int or power not in (1,2):
        raise ValueError("genuine original W32/W34 finite source oracle only")
    s,V,flags=genuine_source(power)
    a=minimal_alphabet(V)
    f=tuple(map(tuple,f));g=tuple(map(tuple,g))
    _verify_typed_injections(a,V,f,g)
    ids=tuple(range(len(flags))) if core_ids is None else tuple(core_ids)
    if (len(set(ids))!=len(ids) or any(type(i) is not int or not 0<=i<len(flags)
                                      for i in ids)):
        raise ValueError("unique valid original source core flag IDs required")
    # Original SOURCE-first compute R0 and its dual separately.
    Rpoint=[[0]*a for _ in range(V)]
    Rline=[[0]*a for _ in range(V)]
    for i in ids:
        p,ell=flags[i]
        for y in g[ell]:Rpoint[p][y]+=1
        for x in f[p]:Rline[ell][x]+=1
    Mg=sum(z*(z-1)//2 for row in Rpoint for z in row)
    Mf=sum(z*(z-1)//2 for row in Rline for z in row)
    source_Qx=2*sum(z*z for row in Rpoint for z in row)
    source_Qy=2*sum(z*z for row in Rline for z in row)
    N0=len(ids)
    if source_Qx!=4*N0+4*Mg or source_Qy!=4*N0+4*Mf:
        raise AssertionError("source pencil collision count failed")
    graph,owner=physical(ids,flags,f,g)
    direct=exact_improper_path_grid_certificate(graph)
    assert len(owner)==2*N0
    if direct["edges"]!=2*N0:
        raise AssertionError("genuine original flag needs two paired diagonals")
    if (source_Qx!=direct["Qx_direct_two_coordinate_returns"] or
        source_Qy!=direct["Qy_direct_two_coordinate_returns"]):
        raise AssertionError("independent original source and physical 2-walk books differ")
    B2=4*N0+4*(Mf+Mg)
    if direct["improper_B2_total_exact"]!=B2:
        raise AssertionError("exact source B2 inclusion-exclusion breaks")
    Delta=direct["maximum_degree"]
    if direct["new_improper_three_upper"]!=Delta*(16*N0+12*(Mf+Mg)):
        raise AssertionError("new all-h improper 3walk upper from source books breaks")
    if direct["new_fourth_upper_given_exact_P2"]!=(
        2*direct["proper_P2_frobenius_squared"]+2*Delta*B2
    ):
        raise AssertionError("new all-h fourth-core transfer breaks")
    return {
        "s":s,"V":V,"a":a,
        "original_core_incidence_flag_count_N0":N0,
        "original_source_Mf":Mf,"original_source_Mg":Mg,
        "original_source_Qx":source_Qx,
        "original_source_Qy":source_Qy,
        "original_source_B2_union_exact":B2,
        "source_and_physical_independent_verification":True,
        "physical":direct,
        "all_h_analytic_claim_based_on_source_degree_not_small_s":True,
    }


